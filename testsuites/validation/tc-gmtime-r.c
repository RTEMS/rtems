static void CTimeReqGmtimeR_Post_Return_Check(
  CTimeReqGmtimeR_Context    *ctx,
  CTimeReqGmtimeR_Post_Return state
)
{
  switch ( state ) {
    case CTimeReqGmtimeR_Post_Return_Result: {
      /*
       * The return value of gmtime_r() shall be the value of the `result`
       * parameter.
       */
      T_eq_ptr( ctx->result, &ctx->tm );
      break;
    }

    case CTimeReqGmtimeR_Post_Return_Null: {
      /*
       * The return value of gmtime_r() shall be NULL.
       */
      T_null( ctx->result );
      break;
    }

    case CTimeReqGmtimeR_Post_Return_NA:
      break;
  }
}

