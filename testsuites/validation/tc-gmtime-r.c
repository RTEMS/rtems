static int64_t GetLastDayOfMonth( int64_t year, unsigned int month )
{
  if ( month == 12 ) {
    return 31;
  }

  return DaysFromCivil( year, month + 1, 1 ) - DaysFromCivil( year, month, 1 );
}

static int GetWeekDay( int64_t days )
{
  int64_t weekday;

  /* The Epoch is a Thursday */
  weekday = ( days + 4 ) % 7;

  if ( weekday < 0 ) {
    weekday += 7;
  }

  return (int) weekday;
}

static void CTimeReqGmtimeR_Pre_Year_Prepare(
  CTimeReqGmtimeR_Context *ctx,
  CTimeReqGmtimeR_Pre_Year state
)
{
  switch ( state ) {
    case CTimeReqGmtimeR_Pre_Year_Least: {
      /*
       * While the time referenced by the `timer` parameter is the least value
       * of type time_t.
       */
      ctx->year_state = YEAR_LEAST;
      break;
    }

    case CTimeReqGmtimeR_Pre_Year_Underflow: {
      /*
       * While the year of the time referenced by the `timer` parameter in the
       * proleptic Gregorian calendar is before the first year which the member
       * tm_year can represent, while the time is greater than the least value
       * of type time_t.
       */
      ctx->year_state = YEAR_UNDERFLOW;
      break;
    }

    case CTimeReqGmtimeR_Pre_Year_First: {
      /*
       * While the year of the time referenced by the `timer` parameter in the
       * proleptic Gregorian calendar is the first year which the member
       * tm_year can represent.
       */
      ctx->year_state = YEAR_FIRST;
      break;
    }

    case CTimeReqGmtimeR_Pre_Year_BeforeEpoch: {
      /*
       * While the year of the time referenced by the `timer` parameter in the
       * proleptic Gregorian calendar is after the first year which the member
       * tm_year can represent and before the year of the Unix epoch.
       */
      ctx->year_state = YEAR_BEFORE_EPOCH;
      break;
    }

    case CTimeReqGmtimeR_Pre_Year_AfterEpoch: {
      /*
       * While the year of the time referenced by the `timer` parameter in the
       * proleptic Gregorian calendar is at or after the year of the Unix epoch
       * and before the last year which the member tm_year can represent.
       */
      ctx->year_state = YEAR_AFTER_EPOCH;
      break;
    }

    case CTimeReqGmtimeR_Pre_Year_Last: {
      /*
       * While the year of the time referenced by the `timer` parameter in the
       * proleptic Gregorian calendar is the last year which the member tm_year
       * can represent.
       */
      ctx->year_state = YEAR_LAST;
      break;
    }

    case CTimeReqGmtimeR_Pre_Year_Overflow: {
      /*
       * While the year of the time referenced by the `timer` parameter in the
       * proleptic Gregorian calendar is after the last year which the member
       * tm_year can represent, while the time is less than the greatest value
       * of type time_t.
       */
      ctx->year_state = YEAR_OVERFLOW;
      break;
    }

    case CTimeReqGmtimeR_Pre_Year_Greatest: {
      /*
       * While the time referenced by the `timer` parameter is the greatest
       * value of type time_t.
       */
      ctx->year_state = YEAR_GREATEST;
      break;
    }

    case CTimeReqGmtimeR_Pre_Year_NA:
      break;
  }
}

