static void CTimeReqGmtimeR_Action( CTimeReqGmtimeR_Context *ctx )
{
  ctx->year = years[ ctx->year_state ][ ctx->leap_year ];

  switch ( ctx->day_state ) {
    case DAY_FIRST:
      ctx->day = 1;
      break;
    case DAY_BETWEEN:
      ctx->day = 15;
      break;
    default:
      ctx->day = GetLastDayOfMonth( ctx->year, ctx->month );
      break;
  }

  ctx->days = DaysFromCivil( ctx->year, ctx->month, ctx->day );

  if ( ctx->year_state == YEAR_LEAST ) {
    ctx->timer = (time_t) INT64_MIN;
  } else if ( ctx->year_state == YEAR_GREATEST ) {
    ctx->timer = (time_t) INT64_MAX;
  } else {
    ctx->timer = (time_t) ctx->days * 86400 + ctx->hour * 3600 +
                 ctx->minute * 60 + ctx->second;
  }
  memset( &ctx->tm, 0xff, sizeof( ctx->tm ) );
  ctx->tm.tm_zone = NULL;
  errno = 0;
  ctx->result = gmtime_r( &ctx->timer, &ctx->tm );
  ctx->errno_value = errno;
}

